import {
  Check,
  Column,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  OneToMany,
  PrimaryGeneratedColumn,
} from 'typeorm';

@Entity('sports')
@Index('UQ_sports_normalized_name', ['normalizedName'], { unique: true })
@Index('IDX_sports_parent_id', ['parentId'])
@Check('CHK_sports_name_not_blank', "CHAR_LENGTH(REPLACE(`name`, ' ', '')) > 0")
export class Sport {
  @PrimaryGeneratedColumn()
  id!: number;

  @Column({ type: 'varchar', length: 180, charset: 'utf8mb4', collation: 'utf8mb4_bin' })
  name!: string;

  // Global uniqueness, including inactive sports: ignore case and ordinary spaces.
  // Generated by MySQL, never supplied or updated by application code.
  @Column({
    name: 'normalized_name',
    type: 'varchar',
    length: 180,
    charset: 'utf8mb4',
    collation: 'utf8mb4_bin',
    asExpression: "LOWER(REPLACE(TRIM(`name`), ' ', ''))",
    generatedType: 'STORED',
    select: false,
    insert: false,
    update: false,
  })
  readonly normalizedName!: string;

  @Column({ type: 'text', nullable: true })
  description!: string | null;

  @Column({ type: 'boolean', default: true })
  active!: boolean;

  @Column({ name: 'parent_id', type: 'int', nullable: true })
  parentId!: number | null;

  // Existence and deletion protection belong to the FK. Cycle validation will
  // belong to the future service; a recursive FK alone cannot enforce a tree.
  @ManyToOne(() => Sport, (sport) => sport.children, {
    nullable: true,
    cascade: false,
    onDelete: 'RESTRICT',
    onUpdate: 'RESTRICT',
    orphanedRowAction: 'disable',
  })
  @JoinColumn({ name: 'parent_id', foreignKeyConstraintName: 'FK_sports_parent_id' })
  parent?: Sport | null;

  @OneToMany(() => Sport, (sport) => sport.parent, { cascade: false })
  children?: Sport[];
}
